export const duration = (t) => {
  if (!t.days) return 'Length to suit you';
  return t.nights ? `${t.days} days, ${t.nights} nights` : `${t.days} days`;
};

// A still for cards and posters: the trip photo, or the video's poster frame.
export const stillOf = (t) =>
  t.tilePhoto || t.photo
    ? { kind: 'photo', photo: t.tilePhoto || t.photo }
    : { kind: 'poster', src: t.video?.poster, alt: t.video?.label || t.name };

// The best time to go, short enough for a fact tile: the first sentence of the season note,
// without its explanation ("October to March, the cooler months" becomes "October to March").
export const bestTime = (t) => t.seasonNote.split('.')[0].replace(/, (the|after) .*/, '');

